<?php

require_once '../includes/config.php';
require '../vendor/autoload.php';

use Dompdf\Dompdf;
use Dompdf\Options;

$options = new Options();

$options->set('isRemoteEnabled', true);

$dompdf = new Dompdf($options);

$pdo = getDB();
$logoPath =
__DIR__.'/../comp-logo/logo.png';

$type =
pathinfo(
    $logoPath,
    PATHINFO_EXTENSION
);

$data =
file_get_contents(
    $logoPath
);

$logo =
'data:image/'.
$type.
';base64,'.
base64_encode(
    $data
);

$filter = $_GET['filter'] ?? 'today';
if($filter=='today'){

    $stmt = $pdo->query("

        SELECT

        e.full_name,

        a.check_in,

        a.check_out,

        a.total_hours

        FROM employee_attendance a

        JOIN employees e

        ON a.employee_id=e.id

        WHERE DATE(a.check_in)=CURDATE()

        ORDER BY a.check_in DESC

    ");

}

elseif($filter=='week'){

    $stmt = $pdo->query("

        SELECT

        e.full_name,

        a.check_in,

        a.check_out,

        a.total_hours

        FROM employee_attendance a

        JOIN employees e

        ON a.employee_id=e.id

        WHERE YEARWEEK(a.check_in)=YEARWEEK(NOW())

        ORDER BY a.check_in DESC

    ");

}

else{

    $stmt = $pdo->query("

        SELECT

        e.full_name,

        a.check_in,

        a.check_out,

        a.total_hours

        FROM employee_attendance a

        JOIN employees e

        ON a.employee_id=e.id

        WHERE MONTH(a.check_in)=MONTH(NOW())

        AND YEAR(a.check_in)=YEAR(NOW())

        ORDER BY a.check_in DESC

    ");

}

$rows = $stmt->fetchAll();
$total=count($rows);

$present=0;

foreach($rows as $row){

if(!$row['check_out']){

$present++;

}

}

$completed=
$total-$present;
$html='

<style>

body{
font-family:Arial,sans-serif;
font-size:12px;
color:#222;
}

.header{
text-align:center;
margin-bottom:20px;
}

.header img{
height:80px;
}

.title{
font-size:28px;
