color:#666;
}
</style>'
;

$html .= '

<div class="header">

<img src="'.$logo.'">

<div class="title">

AMBITIOUS GROUP

</div>

<div class="subtitle">

Employee Attendance Report

</div>

</div>

<hr>

';
$html .= '

<b>Filter:</b>

'.ucfirst($filter).'

<br><br>

<b>Generated:</b>

'.date('d M Y h:i A').'

<hr>

';
$html .= '

<table>

<tr>
<th>Total Employees</th>
<th>Present</th>
<th>Completed</th>

</tr>

<tr>

<td>'.$total.'</td>

<td>'.$present.'</td>

<td>'.$completed.'</td>

</tr>

</table>

<br><br>

';
$html .= '

<table>

<tr>

<th>Employee</th>

<th>Check In</th>

<th>Check Out</th>

<th>Total Hours</th>

</tr>

';
foreach($rows as $row){

$html .= '

<tr>

<td>'.$row['full_name'].'</td>

<td>'.date(
'h:i A',
strtotime($row['check_in'])
).'</td>

<td>'.

(
$row['check_out']

?

date(
'h:i A',
strtotime($row['check_out'])
)

:

'-'

)

.'</td>

<td>'.

(
$row['total_hours']

?

$row['total_hours']

:

'-'

)

.'</td>

</tr>

';

}
$html .= '

</table>

<br><br><br>

<div style="margin-top:50px">

<table style="width:100%;border:none">

<tr>

<td style="border:none;text-align:left">

